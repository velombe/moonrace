// Copies country flag SVGs (flag-icons, MIT) to public/flags and writes the
// country list used by the planting UI. Usage: npm run flags
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const root = dirname(require.resolve("flag-icons/package.json"));
const countries = JSON.parse(readFileSync(join(root, "country.json"), "utf8"))
  .filter((c) => c.iso)
  .sort((a, b) => a.name.localeCompare(b.name));

mkdirSync("public/flags", { recursive: true });
for (const c of countries) copyFileSync(join(root, "flags/4x3", `${c.code}.svg`), `public/flags/${c.code}.svg`);
copyFileSync(join(root, "LICENSE"), "public/flags/LICENSE.txt");

const list = countries.map((c) => `  [${JSON.stringify(c.code)}, ${JSON.stringify(c.name)}],`).join("\n");
writeFileSync(
  "lib/countries.ts",
  `// Generated by scripts/copy-flags.mjs from flag-icons (MIT). Do not edit by hand.\n` +
    `/** [ISO 3166-1 alpha-2 code, name]; flag image at /flags/<code>.svg */\n` +
    `export const COUNTRIES: [code: string, name: string][] = [\n${list}\n];\n`,
);
console.log(`Copied ${countries.length} flags to public/flags`);
